export function getCurriculumPlaylistContext(videoId: string): PlaylistContext | null {
  if (!videoId) return null;
  const cleanId = videoId.startsWith('video_note_') ? videoId.replace('video_note_', '') : videoId;

  // 1. Check AI_DATA_SCIENCE_COURSES (individual lessons)
  for (const course of AI_DATA_SCIENCE_COURSES) {
    if (course.videos && course.videos.length > 0) {
      const idx = course.videos.findIndex((v) => v.id === cleanId);
      if (idx !== -1) {
        const mappedVideos: StudyTheaterVideo[] = course.videos.map((v) => ({
          id: v.id,
          title: v.title,
          youtubeUrl: v.youtubeUrl,
          subject: course.category || course.title,
          category: 'genai',
          difficulty: course.tier,
          duration: v.durationTimestamp,
          thumbnailUrl: v.thumbnailUrl,
          description: v.description,
          startSeconds: v.startSeconds || 0,
        }));
        return {
          courseId: course.id,
          courseTitle: course.title,
          currentIndex: idx,
          totalCount: mappedVideos.length,
          prevVideo: idx > 0 ? mappedVideos[idx - 1] : null,
          nextVideo: idx < mappedVideos.length - 1 ? mappedVideos[idx + 1] : null,
          videos: mappedVideos,
        };
      }
    }
  }

  // 2. Check if videoId is a Course itself
  const courseIdx = AI_DATA_SCIENCE_COURSES.findIndex((c) => c.id === cleanId);
  if (courseIdx !== -1) {
    const course = AI_DATA_SCIENCE_COURSES[courseIdx];
    if (course.videos && course.videos.length > 0) {
      const mappedVideos: StudyTheaterVideo[] = course.videos.map((v) => ({
        id: v.id,
        title: v.title,
        youtubeUrl: v.youtubeUrl,
        subject: course.category || course.title,
        category: 'genai',
        difficulty: course.tier,
        duration: v.durationTimestamp,
        thumbnailUrl: v.thumbnailUrl,
        description: v.description,
        startSeconds: v.startSeconds || 0,
      }));
      return {
        courseId: course.id,
        courseTitle: course.title,
        currentIndex: 0,
        totalCount: mappedVideos.length,
        prevVideo: null,
        nextVideo: mappedVideos.length > 1 ? mappedVideos[1] : null,
        videos: mappedVideos,
      };
    }
  }

  // 3. Check DSA_PROBLEMS_DATA
  const dsaIdx = DSA_PROBLEMS_DATA.findIndex((p) => p.id === cleanId);
  if (dsaIdx !== -1) {
    const currentProb = DSA_PROBLEMS_DATA[dsaIdx];
    const chapterProblems = DSA_PROBLEMS_DATA.filter(
      (p) => p.moduleIndex === currentProb.moduleIndex && p.youtubeUrl
    );
    const chapterIdx = chapterProblems.findIndex((p) => p.id === cleanId);
    if (chapterIdx !== -1) {
      const mappedVideos: StudyTheaterVideo[] = chapterProblems.map((p) => ({
        id: p.id,
        title: p.title,
        youtubeUrl: p.youtubeUrl!,
        subject: `Ch ${p.moduleIndex}: ${p.moduleName}`,
        category: 'dsa',
        difficulty: p.difficulty,
        startSeconds: 0,
      }));
      return {
        courseId: `dsa-ch-${currentProb.moduleIndex}`,
        courseTitle: `Ch ${currentProb.moduleIndex}: ${currentProb.moduleName}`,
        currentIndex: chapterIdx,
        totalCount: mappedVideos.length,
        prevVideo: chapterIdx > 0 ? mappedVideos[chapterIdx - 1] : null,
        nextVideo: chapterIdx < mappedVideos.length - 1 ? mappedVideos[chapterIdx + 1] : null,
        videos: mappedVideos,
      };
    }
  }

  return null;
}

export function parseTimestampToSeconds(ts: string): number {
  if (!ts) return 0;
  const clean = ts.replace(/[\[\]@\(\)]/g, '').trim();

  // Match mm:ss or hh:mm:ss or m:ss
  const colonMatch = clean.match(/\b(\d{1,2}):(\d{2})(?::(\d{2}))?\b/);
  if (colonMatch) {
    if (colonMatch[3] !== undefined) {
      // hh:mm:ss
      const h = parseInt(colonMatch[1], 10);
      const m = parseInt(colonMatch[2], 10);
      const s = parseInt(colonMatch[3], 10);
      return h * 3600 + m * 60 + s;
    } else {
      // mm:ss
      const m = parseInt(colonMatch[1], 10);
      const s = parseInt(colonMatch[2], 10);
      return m * 60 + s;
    }
  }

  // Match 4m15s or 4m or 30s
  const minMatch = clean.match(/(\d+)\s*m(?:in)?/i);
  const secMatch = clean.match(/(\d+)\s*s(?:ec)?/i);
  if (minMatch || secMatch) {
    const m = minMatch ? parseInt(minMatch[1], 10) : 0;
    const s = secMatch ? parseInt(secMatch[1], 10) : 0;
    return m * 60 + s;
  }

  // Plain digits
  const rawDigits = clean.match(/^\d+$/);
  if (rawDigits) {
    return parseInt(rawDigits[0], 10);
  }

  return 0;
}

export function formatSecondsToTimestamp(secs: number): string {
  const safeSecs = Math.max(0, Math.floor(isNaN(secs) ? 0 : secs));
  const h = Math.floor(safeSecs / 3600);
  const m = Math.floor((safeSecs % 3600) / 60);
  const s = safeSecs % 60;
  if (h > 0) {
    return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
  }
  return `${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
}

export function parseMarkdownToTimestampNotes(raw: string): ITimestampNote[] {
  if (!raw || !raw.trim()) return [];
  const lines = raw.split('\n');
  const results: ITimestampNote[] = [];

  lines.forEach((line, index) => {
    const trimmed = line.trim();
    if (!trimmed) return;

    // Look for timestamp pattern
    const match = trimmed.match(/(?:\[|@|\(|\b)(\d{1,2}:\d{2}(?::\d{2})?)(?:\]|\)|\b)/);
    if (match) {
      const tsFormatted = match[1];
      const tsSecs = parseTimestampToSeconds(tsFormatted);
      const isRevisit =
        trimmed.includes('⚠️') ||
        trimmed.toLowerCase().includes('revisit') ||
        trimmed.toLowerCase().includes('confusion') ||
        trimmed.toLowerCase().includes('doubt');

      // Clean the note text
      let noteText = trimmed
        .replace(/(?:\[|@|\()?\d{1,2}:\d{2}(?::\d{2})?(?:\]|\))?/, '')
        .replace(/^[-\*\•\d\.\s]+/, '')
        .replace(/⚠️/g, '')
        .replace(/^[-\s:]+/, '')
        .trim();

      if (!noteText) {
        noteText = 'Key concept / bookmark';
      }

      results.push({
        id: `ts_note_${Date.now()}_${index}`,
        timestampSeconds: tsSecs,
        timestampFormatted: formatSecondsToTimestamp(tsSecs),
        note: noteText,
        isRevisit,
        createdAt: Date.now() - (lines.length - index) * 1000,
      });
    }
  });

  return results.sort((a, b) => a.timestampSeconds - b.timestampSeconds);
}


